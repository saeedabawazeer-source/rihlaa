export const getTranslation = (key, lang = 'en') => {
  const dictionary = TRANSLATIONS[lang] || TRANSLATIONS['en'];
  return dictionary[key] || TRANSLATIONS['en'][key] || key;
};

export const getDir = (lang = 'en') => {
  return lang === 'ar' ? 'rtl' : 'ltr';
};

export const getItemText = (val, lang = 'en') => {
  if (!val) return '';
  if (typeof val === 'string') return val;
  if (typeof val === 'object') {
    return val[lang] || val.en || val.ar || Object.values(val)[0] || '';
  }
  return String(val);
};

export const getItemList = (val, lang = 'en') => {
  if (!val) return [];
  if (Array.isArray(val)) return val;
  if (typeof val === 'object') {
    return val[lang] || val.en || val.ar || [];
  }
  return [];
};

